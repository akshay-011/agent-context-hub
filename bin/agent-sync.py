#!/usr/bin/env python3
"""
agent-sync.py - Universal Context Compiler for AI Coding Agents.
Compiles human-curated Obsidian notes into native, lightweight configs for:
- AGY (Antigravity CLI)
- Claude Code
- Cursor / Windsurf
- OpenCode / Codex
- Universal AGENTS.md standard
"""

import os
import re
import sys
import argparse
import subprocess
from pathlib import Path

try:
    import yaml
except ImportError:
    print("[ERROR] PyYAML is required. Install with: pip install pyyaml or pacman -S python-yaml", file=sys.stderr)
    sys.exit(1)

AUTO_HEADER = (
    "# ---------------------------------------------------------------------------\n"
    "# AUTO-GENERATED BY agent-sync - DO NOT EDIT DIRECTLY\n"
    "# Edit source notes in your Obsidian Context directory.\n"
    "# ---------------------------------------------------------------------------\n\n"
)

def find_context_dir(user_specified=None):
    """Discovers the active Context directory using precedence order."""
    candidates = []
    if user_specified:
        candidates.append(Path(user_specified).expanduser())
    if os.environ.get("AGENT_CONTEXT_DIR"):
        candidates.append(Path(os.environ["AGENT_CONTEXT_DIR"]).expanduser())

    config_file = Path.home() / ".config" / "agent-context" / "config.yaml"
    if config_file.exists():
        try:
            with open(config_file, "r", encoding="utf-8") as f:
                cfg = yaml.safe_load(f) or {}
                if cfg.get("context_dir"):
                    candidates.append(Path(cfg["context_dir"]).expanduser())
        except Exception as e:
            print(f"[WARN] Failed reading config {config_file}: {e}", file=sys.stderr)

    # Repository-relative directory
    repo_context = Path(__file__).resolve().parent.parent / "context"
    candidates.append(repo_context)

    # Standard user locations
    candidates.append(Path.home() / "Vault" / "Context")
    candidates.append(Path.home() / "Documents" / "Vault" / "Context")
    candidates.append(Path.home() / "workspace" / "agent-context-hub" / "context")

    for candidate in candidates:
        if candidate.exists() and candidate.is_dir():
            return candidate.resolve()

    return repo_context

def clean_obsidian_markdown(content: str) -> str:
    """Strips Obsidian-specific syntax, comments, and private tags."""
    # Convert [[Note Name|Display Text]] -> Display Text
    content = re.sub(r'\[\[(?:[^|\]]*\|)?([^\]]+)\]\]', r'\1', content)
    # Strip Obsidian inline/multiline comments %% ... %%
    content = re.sub(r'%%.*?%%', '', content, flags=re.DOTALL)
    # Strip blocks marked <!-- private --> ... <!-- /private -->
    content = re.sub(r'<!--\s*private\s*-->.*?<!--\s*/private\s*-->', '', content, flags=re.DOTALL | re.IGNORECASE)
    # Remove lines tagged with #private
    lines = [line for line in content.splitlines() if not re.search(r'(?<!\S)#private(?!\S)', line)]
    return "\n".join(lines).strip()

def parse_markdown(file_path: Path):
    """Extracts frontmatter and cleans markdown body."""
    text = file_path.read_text(encoding='utf-8')
    frontmatter = {}
    body = text
    if text.startswith('---'):
        parts = text.split('---', 2)
        if len(parts) >= 3:
            try:
                frontmatter = yaml.safe_load(parts[1]) or {}
                body = parts[2]
            except Exception as e:
                print(f"[WARN] Failed parsing YAML frontmatter in {file_path}: {e}", file=sys.stderr)
    return frontmatter, clean_obsidian_markdown(body)

def estimate_tokens(text: str) -> int:
    """Rough approximation of tokens (~4 chars per token)."""
    return len(text) // 4

def sync_global(context_dir: Path, dry_run=False):
    """Compiles global context into ~/.claude/, ~/.gemini/config/, and ~/.codex/."""
    global_dir = context_dir / "global"
    if not global_dir.exists():
        print(f"[WARN] Global context directory not found at {global_dir}", file=sys.stderr)
        return

    snippets = []
    for md_file in sorted(global_dir.glob("*.md")):
        _, body = parse_markdown(md_file)
        if body:
            snippets.append(f"<!-- Source: {md_file.name} -->\n{body}")

    compiled = AUTO_HEADER + "\n\n".join(snippets) + "\n"
    tokens = estimate_tokens(compiled)

    targets = [
        (Path.home() / ".claude" / "CLAUDE.md", "Claude Code Global"),
        (Path.home() / ".gemini" / "config" / "instructions.md", "AGY / Antigravity Instructions"),
        (Path.home() / ".gemini" / "config" / "GEMINI.md", "AGY / Antigravity Global Rules"),
        (Path.home() / ".gemini" / "GEMINI.md", "AGY / Antigravity Home Rules"),
        (Path.home() / ".codex" / "instructions.md", "Codex / OpenCode Global"),
    ]

    print(f"\n[GLOBAL SYNC] Source: {context_dir} (~{tokens} tokens, {len(snippets)} modules)")
    for target_path, label in targets:
        if dry_run:
            print(f"  [DRY-RUN] Would write {label} -> {target_path}")
            continue
        try:
            target_path.parent.mkdir(parents=True, exist_ok=True)
            target_path.write_text(compiled, encoding='utf-8')
            print(f"  ✓ {label:<24} -> {target_path}")
        except Exception as e:
            print(f"  ✗ Failed writing {target_path}: {e}", file=sys.stderr)

def sync_workspace(context_dir: Path, workspace_path: Path, dry_run=False):
    """Compiles workspace context (AGENTS.md, .cursor/rules/*.mdc, CLAUDE.md link)."""
    repo = workspace_path.resolve()
    if not repo.exists() or not repo.is_dir():
        print(f"[ERROR] Workspace path '{workspace_path}' is not a valid directory.", file=sys.stderr)
        return

    print(f"\n[WORKSPACE SYNC] Target: {repo}")

    # Gather global core rules for header
    global_dir = context_dir / "global"
    global_snippets = []
    if global_dir.exists():
        for md_file in sorted(global_dir.glob("*.md")):
            _, body = parse_markdown(md_file)
            if body:
                global_snippets.append(body)

    # 1. Compile universal AGENTS.md
    agents_lines = [
        AUTO_HEADER,
        "# AGENTS.md - Cross-Agent Operational Directives\n",
        "## Core Developer Profile",
        "\n\n".join(global_snippets),
        "\n## Workspace Directives",
        "- Verify all modifications with relevant automated test suites before task completion.",
        "- Follow established codebase conventions and avoid introducing breaking changes without explicit shims.\n"
    ]
    agents_text = "\n".join(agents_lines)
    agents_file = repo / "AGENTS.md"
    if not dry_run:
        agents_file.write_text(agents_text, encoding='utf-8')
        print(f"  ✓ Universal Directives    -> {agents_file}")
    else:
        print(f"  [DRY-RUN] Would write {agents_file}")

    # 2. Link or create CLAUDE.md and GEMINI.md
    for link_name in ["CLAUDE.md", "GEMINI.md"]:
        link_file = repo / link_name
        if not link_file.exists() and not dry_run:
            try:
                link_file.symlink_to("AGENTS.md")
                print(f"  ✓ Symlink ({link_name:<10}) -> AGENTS.md")
            except Exception:
                link_file.write_text(agents_text, encoding='utf-8')
                print(f"  ✓ Direct File ({link_name:<10}) -> {link_file}")

    # 3. Generate Cursor .cursor/rules/*.mdc with globs
    stacks_dir = context_dir / "stacks"
    cursor_dir = repo / ".cursor" / "rules"
    if stacks_dir.exists():
        if not dry_run:
            cursor_dir.mkdir(parents=True, exist_ok=True)
        for stack_file in sorted(stacks_dir.glob("*.md")):
            fm, body = parse_markdown(stack_file)
            globs = fm.get("globs", "")
            description = fm.get("description", f"Rules for {stack_file.stem}")
            always_apply = "true" if not globs else "false"

            mdc_content = (
                f"---\n"
                f"description: {description}\n"
                f"globs: {globs}\n"
                f"alwaysApply: {always_apply}\n"
                f"---\n"
                f"{AUTO_HEADER}\n"
                f"{body}\n"
            )
            out_file = cursor_dir / f"{stack_file.stem}.mdc"
            if not dry_run:
                out_file.write_text(mdc_content, encoding='utf-8')
                print(f"  ✓ Cursor Rule ({stack_file.stem:<15}) -> {out_file}")
            else:
                print(f"  [DRY-RUN] Would generate Cursor rule {out_file}")

def print_status(context_dir: Path):
    """Displays active rules, token counts, and daemon status."""
    print("=" * 60)
    print(" AGENT CONTEXT HUB: STATUS & HEALTH CHECK")
    print("=" * 60)
    print(f"Active Context Directory: {context_dir}")
    print(f"Context Directory Exists: {context_dir.exists()}")

    # Check files
    global_dir = context_dir / "global"
    if global_dir.exists():
        modules = list(global_dir.glob("*.md"))
        print(f"\nGlobal Modules ({len(modules)}):")
        total_tokens = 0
        for m in sorted(modules):
            _, body = parse_markdown(m)
            tokens = estimate_tokens(body)
            total_tokens += tokens
            print(f"  - {m.name:<25} (~{tokens:>4} tokens)")
        print(f"  Total Estimated Global Tokens: ~{total_tokens} (Target: < 500)")

    stacks_dir = context_dir / "stacks"
    if stacks_dir.exists():
        stacks = list(stacks_dir.glob("*.md"))
        print(f"\nStack Playbooks ({len(stacks)}):")
        for s in sorted(stacks):
            fm, _ = parse_markdown(s)
            globs = fm.get("globs", "always-active")
            print(f"  - {s.name:<25} (globs: {globs})")

    adrs_dir = context_dir / "adrs"
    if adrs_dir.exists():
        adrs = list(adrs_dir.glob("*.md"))
        print(f"\nDeep ADRs ({len(adrs)}): [Accessible via MCP on-demand]")
        for a in sorted(adrs):
            print(f"  - {a.name}")

    # Check systemd daemon status
    print("\nDaemon / Watcher Status:")
    try:
        res = subprocess.run(["systemctl", "--user", "is-active", "agent-sync.path"],
                             capture_output=True, text=True)
        is_active = res.stdout.strip()
        print(f"  systemd path unit (agent-sync.path): {is_active.upper()}")
    except Exception as e:
        print(f"  systemd check failed: {e}")

    try:
        linger = subprocess.run(["loginctl", "show-user", os.environ.get("USER", "akshay"), "--property=Linger"],
                                capture_output=True, text=True)
        print(f"  Linger (boot persistence): {linger.stdout.strip()}")
    except Exception:
        pass
    print("=" * 60)

def main():
    parser = argparse.ArgumentParser(description="Universal AI Coding Agent Context Synchronizer")
    parser.add_argument("--context-dir", "-c", help="Path to Obsidian Context directory")
    parser.add_argument("--workspace", "-w", help="Compile rules for a specific workspace repository")
    parser.add_argument("--global-only", "-g", action="store_true", help="Sync only global agent instructions")
    parser.add_argument("--dry-run", "-n", action="store_true", help="Preview output paths without writing files")
    parser.add_argument("--status", "-s", action="store_true", help="Show context health and daemon status")

    args = parser.parse_args()

    context_dir = find_context_dir(args.context_dir)

    if args.status:
        print_status(context_dir)
        return

    # Always perform global sync unless workspace is explicitly passed without global-only
    sync_global(context_dir, dry_run=args.dry_run)

    if args.workspace:
        sync_workspace(context_dir, Path(args.workspace), dry_run=args.dry_run)

    print("\n✓ Sync complete. All agents aligned.")

if __name__ == "__main__":
    main()
